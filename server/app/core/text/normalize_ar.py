"""التطبيع العربي للفهرسة والبحث والمطابقة (Section 7.3)."""

import re
import unicodedata

# 1. إزالة التشكيل (Tashkeel: U+064B - U+065F) والتنوين والألف الخنجرية (U+0670)
TASHKEEL_REGEX = re.compile(r"[\u064B-\u065F\u0670]")

# 2. إزالة التطويل والكشيدة (Tatweel: U+0640)
TATWEEL_REGEX = re.compile(r"\u0640+")

# 3. جدول تحويل الأرقام المشرقية والفارسية إلى ASCII
NUMERALS_MAP = str.maketrans({
    "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4",
    "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9",
    "۰": "0", "۱": "1", "۲": "2", "۳": "3", "۴": "4",
    "۵": "5", "۶": "6", "۷": "7", "۸": "8", "۹": "9",
})

# 4. جدول توحيد الألف والهمزات والتاء المربوطة والياء
CHAR_MAP = str.maketrans({
    "أ": "ا",
    "إ": "ا",
    "آ": "ا",
    "ٱ": "ا",
    "ة": "ه",
    "ى": "ي",
    "ؤ": "و",
    "ئ": "ي",
})


def normalize_ar(text: str) -> str:
    """تطبيع النص العربي وفقاً للمواصفة القياسية في Section 7.3.

    - إزالة التشكيل والتطويل.
    - توحيد أشكال الألف والهمزات والتاء المربوطة.
    - تحويل الأرقام الهندية/الفارسية إلى ASCII.
    - تحويل الحروف الإنجليزية إلى lowercase وتوحيد المسافات.
    """
    if not text:
        return ""

    # تحويل محارف Unicode وتوحيد التشفير
    s = unicodedata.normalize("NFKC", text)

    # 1. إزالة التشكيل والتطويل
    s = TASHKEEL_REGEX.sub("", s)
    s = TATWEEL_REGEX.sub("", s)

    # 2. تحويل الأرقام
    s = s.translate(NUMERALS_MAP)

    # 3. توحيد الحروف
    s = s.translate(CHAR_MAP)

    # 4. تحويل الحروف اللاتينية إلى lowercase
    s = s.lower()

    # 5. توحيد المسافات وتقليم الأطراف
    s = re.sub(r"\s+", " ", s).strip()

    return s
